"""Regenerate the files derived from the code: the JSON Schema, the input-format reference, the
rule catalogue and the conformance table.

    make docs                          # write them
    python scripts/generate.py --check # exit 1 if a committed file is out of date

tests/test_generated.py fails when a committed file differs from what this script writes, so the
documentation cannot drift from the contract, the rules or the fixtures.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from dpa_review.checks import (  # noqa: E402
    ABSENCE_MARKERS,
    ADEQUACY,
    EEA,
    SUBPROCESSOR_TRANSFER,
    assess_transfer,
    run_all_checks,
    subprocessor_rule_id,
)
from dpa_review.contract import CONTRACT, MECHANISMS, Field, format_path, schema_text  # noqa: E402
from dpa_review.facts import rule_facts  # noqa: E402

FIXTURES = ROOT / "tests" / "fixtures"
GENERATED_NOTE = "<!-- Generated by scripts/generate.py (make docs). Do not edit by hand. -->"

_KIND = {
    "flag": "boolean",
    "text": "string",
    "name": "non-empty string",
    "description": "string or boolean",
    "country": "country code",
    "choice": "one of {options}",
    "labels": "list of strings",
    "countries": "list of country codes",
    "section": "object",
    "entries": "list of objects",
    "by_country": "object keyed by country code",
    "evidence": "object keyed by fact path",
}

MINIMAL_INPUT = {
    "processing": {},
    "art28_clauses": {},
    "breach_notification": {},
    "subprocessors": [],
    "transfers": {"destinations": []},
}


def _type(spec: Field) -> str:
    text = _KIND[spec.kind].format(options=", ".join(f"`{option}`" for option in spec.options))
    if spec.kind == "by_country" and spec.value is not None:
        text += " → " + _type(spec.value)
    if not spec.required and spec.nullable and spec.kind not in {"section", "entries", "evidence"}:
        text += ", or null"
    return text


def _cell(text: str) -> str:
    """Text for a Markdown table cell; GitHub would drop <country> as an unknown HTML tag."""
    return text.replace("|", "\\|").replace("<", "&lt;").replace(">", "&gt;")


def input_format() -> str:
    lines = [
        GENERATED_NOTE,
        "",
        "# Input format",
        "",
        "`dpa-review` reviews a structured JSON description of one Data Processing Agreement, not the "
        "contract text. This page lists every key the input may contain. The same contract is published "
        "as JSON Schema in [`schema/dpa.schema.json`](../schema/dpa.schema.json) (also printed by "
        "`dpa-review --schema`), and both are generated from "
        "[`src/dpa_review/contract.py`](../src/dpa_review/contract.py).",
        "",
        "## How input is checked",
        "",
        "Every input is checked against the contract before any rule runs. Input that breaks it exits "
        "`3` and no review state is decided, because a key the rules do not see would otherwise read as "
        "\"not recorded\": a misspelt `\"transfer\"` section once made a DPA with a US transfer come out "
        "`CLEARED_FOR_REVIEW` with exit `0`. Each problem is reported with its line, for example:",
        "",
        "```text",
        "error: dpa.json breaks the input contract, so no review state was decided (2 problems):",
        "  line 43: unknown key 'transfer'; did you mean 'transfers'?",
        "  line 1: missing required key 'transfers': record \"transfers\": {\"destinations\": []} if the "
        "processor makes no direct transfer.",
        "```",
        "",
        "- An unknown key, at any level, is refused, with the closest known key as a suggestion.",
        "- A required section or key that is missing or `null` is refused. Record an absence explicitly "
        "(`[]`, `false`, `\"none\"`) instead of leaving the key out.",
        "- A value of the wrong JSON type is refused: the string `\"false\"` is not a boolean.",
        "- A processing description (`processing.subject_matter`, `processing.duration`, "
        "`processing.nature_and_purpose`) that is blank, or that is only "
        + ", ".join(f"`{marker}`" for marker in ABSENCE_MARKERS[:-1])
        + f" or `{ABSENCE_MARKERS[-1]}` in any case and with any surrounding whitespace, is refused: it "
        "states nothing, but would read as a stated description. Record `false` when the DPA does not "
        "state it. Only these whole values are refused; any other wording is read as a description.",
        "- Country codes are upper-case ISO 3166-1 alpha-2 codes. `UK`, `EL` and `EU` are refused with "
        "the code to use instead (`GB`, `GR`, a member state).",
        "- Every key of `transfers.mechanisms` must be a country that `transfers.destinations` lists.",
        "- Sub-processor names must differ, ignoring case, spaces and punctuation, because rule ids are "
        "derived from them.",
        "- Every `evidence` key must name a fact the input records.",
        "",
        "A flag that is `false`, `null` or omitted reads as \"the DPA does not contain this\", so a clause "
        "you could not find fails closed.",
        "",
        "## The smallest valid input",
        "",
        "```json",
        json.dumps(MINIMAL_INPUT, indent=2),
        "```",
        "",
        "It is valid, and `BLOCKED`: it records no Art. 28 clause. "
        "[`data/sample_dpa.json`](../data/sample_dpa.json) is a complete example, and "
        f"[`tests/fixtures/`](../tests/fixtures/) holds {len(load_expected())} more.",
        "",
        "## Keys",
        "",
    ]
    for key, spec in CONTRACT.items():
        if spec.kind in {"section", "entries"}:
            continue
        if key == "evidence":
            continue
        lines.append(f"- `{key}` ({_type(spec)}{', required' if spec.required else ''}): {_cell(spec.description)}")
    lines.append("")
    for key, spec in CONTRACT.items():
        if spec.kind not in {"section", "entries"}:
            continue
        shape = "a list of objects" if spec.kind == "entries" else "an object"
        lines += [
            f"### `{key}`",
            "",
            f"{'Required' if spec.required else 'Optional'}, {shape}. {_cell(spec.description)}",
            "",
            "| Key | Type | Required | Meaning |",
            "| --- | --- | --- | --- |",
        ]
        for name, field in spec.fields.items():
            prefix = f"{key}[]." if spec.kind == "entries" else f"{key}."
            lines.append(
                f"| `{prefix}{name}` | {_cell(_type(field))} | {'yes' if field.required else 'no'} "
                f"| {_cell(field.description)} |"
            )
        lines.append("")
    lines += [
        "### `evidence`",
        "",
        f"Optional. {CONTRACT['evidence'].description}",
        "",
        "Each value has a `clause` (where the fact is in the DPA, such as `\"§ 7.2\"` or `\"Annex 3\"`), a "
        "`quote` (the DPA's own words, verbatim), or both. A key may name a single fact "
        "(`\"art28_clauses.subprocessor_flowdown\"`), a list item (`\"subprocessors[1]\"`, which also covers "
        "that sub-processor's country and mechanism) or a whole section. The Markdown packet then gains a "
        "\"Source in the DPA\" column, and each finding in the JSON packet an `evidence` list.",
        "",
        "```json",
        json.dumps(
            {
                "evidence": {
                    "art28_clauses.subprocessor_flowdown": {
                        "clause": "§ 7.2",
                        "quote": "The Processor shall impose the same data protection obligations as set out "
                        "in this Agreement on every Sub-processor.",
                    },
                    "subprocessors[0]": {"clause": "Annex 3"},
                }
            },
            indent=2,
            ensure_ascii=False,
        ),
        "```",
        "",
    ]
    return "\n".join(lines)


def _probe(present: bool) -> dict:
    """An input that makes every rule fire once, with every fact present or every fact absent."""
    flags = {
        key: present
        for key in CONTRACT["art28_clauses"].fields
        if key != "subprocessor_authorization"
    }
    return {
        "processing": {
            "subject_matter": present,
            "duration": present,
            "nature_and_purpose": present,
            "data_types": ["contact data"] if present else [],
        },
        "art28_clauses": {**flags, "subprocessor_authorization": "general" if present else "none"},
        "breach_notification": {"processor_notifies_controller": present, "timing": "without undue delay"},
        "subprocessors": [{"name": "<name>", "country": "<COUNTRY>", "transfer_mechanism": "sccs"}],
        "transfers": {
            "destinations": ["<COUNTRY>"],
            "mechanisms": {"<COUNTRY>": "sccs"},
            "transfer_impact_assessment": present,
        },
        "ccpa": {"service_provider_terms": present},
    }


# The rule id of the probe's sub-processor, "<name>", shown with its placeholder.
_SUBPROCESSOR_RULE = SUBPROCESSOR_TRANSFER + "<name>"


def _reads(rule_id: str, dpa: dict) -> str:
    if rule_id == "transfer.<country>":
        return "`transfers.destinations`, `transfers.mechanisms.<COUNTRY>`"
    if rule_id == _SUBPROCESSOR_RULE:
        return "`subprocessors[].country`, `subprocessors[].transfer_mechanism`"
    return ", ".join(f"`{format_path(path)}`" for path in rule_facts(dpa, rule_id))


def rules() -> str:
    present, absent = _probe(True), _probe(False)
    when_absent = {finding.rule_id: finding for finding in run_all_checks(absent)}
    lines = [
        GENERATED_NOTE,
        "",
        "# Rule catalogue",
        "",
        "Every rule `dpa-review` runs, generated from the rules in "
        "[`src/dpa_review/checks.py`](../src/dpa_review/checks.py). A finding is open when its status is "
        "`MISSING` or `NEEDS_REVIEW`. Any open `HIGH` finding makes the packet `BLOCKED` (exit `2`); any "
        "other open finding makes it `NEEDS_REVIEW` (exit `1`); otherwise it is `CLEARED_FOR_REVIEW` "
        "(exit `0`), which still needs a lawyer's sign-off. Input keys are described in "
        "[input-format.md](input-format.md).",
        "",
        "| Rule | Finding | Citation | Severity | Status when the fact is absent | Reads |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for finding in run_all_checks(present):
        rule_id = finding.rule_id
        if rule_id == subprocessor_rule_id("<name>"):
            rule_id = _SUBPROCESSOR_RULE
        if rule_id.startswith("transfer.") and rule_id != "transfer.impact_assessment":
            severity, absent_status = "by transfer basis, see below", "see below"
        else:
            absent_finding = when_absent.get(rule_id)
            severity = finding.severity
            absent_status = (
                f"{absent_finding.status} ({absent_finding.severity})" if absent_finding else "not checked"
            )
        if rule_id == "transfer.impact_assessment":
            absent_status += "; checked only when SCCs or BCR are relied on"
        lines.append(
            f"| `{rule_id}` | {_cell(finding.title)} | {_cell(finding.citation)} | {severity} "
            f"| {absent_status} | {_reads(rule_id, present)} |"
        )
    lines += [
        "",
        "## Transfer rules by basis",
        "",
        "`transfer.<country>` checks each direct destination and `transfer.subprocessor.<name>` each "
        "sub-processor outside the EEA. In the rule id, `<name>` is the sub-processor's name in lower "
        "case (Unicode case folding), with each run of characters other than letters and digits "
        f"replaced by one underscore: \"Support Tools, LLC\" gives `{subprocessor_rule_id('Support Tools, LLC')}`. "
        "Both rules use the same assessment of the country and the recorded mechanism (status and severity):",
        "",
        "| Destination | " + " | ".join(f"`{mechanism}`" for mechanism in MECHANISMS) + " |",
        "| --- |" + " --- |" * len(MECHANISMS),
    ]
    for label, country in (
        ("EEA member state (e.g. DE)", "DE"),
        ("Adequacy country (e.g. JP)", "JP"),
        ("Other third country (e.g. US)", "US"),
    ):
        cells = []
        for mechanism in MECHANISMS:
            status, severity, _ = assess_transfer(country, mechanism)
            cells.append(f"{status} ({severity})")
        lines.append(f"| {label} | " + " | ".join(cells) + " |")
    lines += [
        "",
        "## Reference data",
        "",
        "The country lists the transfer rules use, as they stand in `checks.py`. They are illustrative "
        "and carry no as-of date yet: verify them against the European Commission's current "
        "[adequacy decisions](https://commission.europa.eu/law/law-topic/data-protection/international-"
        "dimension-data-protection/adequacy-decisions_en) before relying on a result.",
        "",
        f"- EEA ({len(EEA)}): " + ", ".join(sorted(EEA)),
        f"- Adequacy (Art. 45) ({len(ADEQUACY)}): " + ", ".join(sorted(ADEQUACY)),
        "",
    ]
    return "\n".join(lines)


def load_expected() -> dict:
    return json.loads((FIXTURES / "expected.json").read_text(encoding="utf-8"))


def conformance() -> str:
    expected = load_expected()
    lines = [
        GENERATED_NOTE,
        "",
        "# Conformance suite",
        "",
        f"{len(expected)} synthetic DPA descriptions in [`tests/fixtures/`](../tests/fixtures/), each with "
        "the review state, exit code and open rules the CLI must produce, recorded in "
        "[`expected.json`](../tests/fixtures/expected.json). "
        "[`tests/test_conformance.py`](../tests/test_conformance.py) runs every fixture through the CLI "
        "on every push, on Python 3.10 to 3.13, and fails on any difference.",
        "",
        "The fixtures freeze what the rules do today. Where a result looks legally questionable it is "
        "flagged below for review rather than changed: a rule change needs a lawyer's sign-off and a "
        "deliberate update of the expected result.",
        "",
        "| Fixture | What it checks | Review state | Exit | Open rules |",
        "| --- | --- | --- | ---: | --- |",
    ]
    for name, case in expected.items():
        state = f"`{case['review_state']}`" if case["review_state"] else "refused (no state)"
        opened = ", ".join(f"`{rule}`" for rule in case.get("open_rules", [])) or (
            "n/a" if case["exit_code"] == 3 else "none"
        )
        flag = " ⚑" if case["legal_review_note"] else ""
        lines.append(
            f"| [`{name}`](../tests/fixtures/{name}){flag} | {_cell(case['checks'])} | {state} "
            f"| {case['exit_code']} | {opened} |"
        )
    flagged = {name: case for name, case in expected.items() if case["legal_review_note"]}
    lines += ["", "## ⚑ Flagged for legal review", ""]
    for name, case in flagged.items():
        lines.append(f"- **`{name}`**: {case['legal_review_note']}")
    lines += [
        "",
        "Run the suite with `make test`, or a single fixture with "
        "`dpa-review --input tests/fixtures/<name> --quiet; echo $?`.",
        "",
    ]
    return "\n".join(lines)


def generated_files() -> dict[Path, str]:
    return {
        ROOT / "schema" / "dpa.schema.json": schema_text(),
        ROOT / "docs" / "input-format.md": input_format(),
        ROOT / "docs" / "rules.md": rules(),
        ROOT / "docs" / "conformance.md": conformance(),
    }


def main(argv: list[str]) -> int:
    stale = []
    for path, content in generated_files().items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == content:
            continue
        if "--check" in argv:
            stale.append(path.relative_to(ROOT).as_posix())
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
            print(f"wrote {path.relative_to(ROOT).as_posix()}")
    if stale:
        print("out of date (run `make docs`): " + ", ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
